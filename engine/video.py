"""Video = chrome (background, HUD, chat input) + timed layers + SFX cues.

frame = f(t): Video.draw(canvas, t) holds no state between frames, so any frame
renders identically no matter where you start.
"""
import math
from dataclasses import dataclass, field

from . import tokens as tk
from .ease import mix, prog, in_out_cubic, out_expo
from .timing import Beat
from .camera import Camera


@dataclass
class Chapter:
    num: int | None        # 0..n for numbered chapters, None for INTRO/recap/outro
    label: str             # "NASKAH"
    start: float
    end: float
    dark: bool = False

    @property
    def color(self):
        return tk.CHAPTER[self.num][0] if self.num is not None else tk.C["accent"]

    @property
    def tint(self):
        return tk.CHAPTER[self.num][1] if self.num is not None else tk.INTRO_TINT

    @property
    def hud(self):
        return f"{self.num:02d} — {self.label}" if self.num is not None else self.label

    @property
    def kicker(self):
        return f"{self.num:02d} · {self.label}" if self.num is not None else self.label


@dataclass
class Layer:
    start: float
    end: float
    fn: object             # fn(c, t)  — t is GLOBAL time
    z: int = 0


@dataclass
class Video:
    duration: float
    bpm: int = tk.M["beat_bpm"]
    beat_offset: float = 0.0
    brand: str = tk.BRAND
    series: str = tk.SERIES
    chapters: list = field(default_factory=list)
    layers: list = field(default_factory=list)
    cues: list = field(default_factory=list)   # (sfx name, t, gain)
    chat: object = None                         # ChatTrack or None
    hud: bool = True
    ground: tuple = None                        # flat background color instead of tinted glows (reel layer: paper)
    camera: object = field(default_factory=Camera)   # applies to layers with z < 80

    def __post_init__(self):
        self.beat = Beat(self.bpm, self.beat_offset)

    # building ---------------------------------------------------------------
    def chapter(self, num, label, start, end, dark=False):
        ch = Chapter(num, label, start, end, dark)
        self.chapters.append(ch)
        self.chapters.sort(key=lambda c: c.start)
        return ch

    def add(self, start, end, fn, z=0):
        """Register fn(c, t) to draw while start <= t < end (include exit time in end!)."""
        self.layers.append(Layer(start, end, fn, z))
        return fn

    def sfx(self, name, t, gain=1.0):
        self.cues.append((name, float(t), float(gain)))

    def all_cues(self):
        """Explicit cues + cues generated by the chat track and cursors."""
        out = list(self.cues)
        if self.chat is not None:
            out += self.chat.cues()
        for extra in getattr(self, "cue_sources", []):
            out += extra.cues()
        return sorted((c for c in out if 0 <= c[1] < self.duration), key=lambda c: c[1])

    def track(self, obj, z=50):
        """Draw an object with .draw(c, t) (e.g. Cursor) over the whole video and collect its .cues()."""
        if not hasattr(self, "cue_sources"):
            self.cue_sources = []
        if hasattr(obj, "cues"):
            self.cue_sources.append(obj)
        self.add(0, self.duration, obj.draw, z)
        return obj

    # queries ----------------------------------------------------------------
    def chapter_at(self, t):
        cur = self.chapters[0] if self.chapters else None
        for ch in self.chapters:
            if ch.start <= t:
                cur = ch
        return cur

    def numbered(self):
        return [c for c in self.chapters if c.num is not None]

    def dark_amount(self, t):
        """0 light → 1 dark, crossfaded around dark chapter edges."""
        d = tk.M["chapter_fade"]
        chs = self.chapters
        if not chs:
            return 0.0
        amt = 1.0 if chs[0].dark else 0.0
        for prev, ch in zip(chs, chs[1:]):
            if ch.dark != prev.dark:  # only crossfade where darkness actually changes
                p = in_out_cubic(prog(t, ch.start - d / 2, d))
                amt += ((1.0 if ch.dark else 0.0) - amt) * p
        return amt

    # drawing ----------------------------------------------------------------
    def draw(self, c, t):
        c.dark = self.dark_amount(t)
        draw_background(c, self, t)
        active = sorted((ly for ly in self.layers if ly.start <= t < ly.end), key=lambda l: l.z)
        for ly in active:  # z < 100: content
            if ly.z < 100:
                self._run(c, ly, t)
        if self.chat is not None:
            self.chat.draw(c, t)
        if self.hud:
            draw_hud(c, self, t)
        for ly in active:  # z >= 100: full-screen overlays above HUD (e.g. black hook card)
            if ly.z >= 100:
                self._run(c, ly, t)

    def _run(self, c, ly, t):
        c.ctx.save()
        if ly.z < 80:  # content moves with the camera; z >= 80 = screen-fixed UI (chips row, overlays)
            self.camera.apply(c.ctx, t)
        ly.fn(c, t)
        c.ctx.restore()


# ── background ──────────────────────────────────────────────────────────
def _tint_at(video, t):
    """Chapter tint, crossfaded over chapter_fade around each boundary."""
    chs = video.chapters
    if not chs:
        return tk.INTRO_TINT
    d = tk.M["chapter_fade"]
    tint = chs[0].tint
    for ch in chs[1:]:
        p = in_out_cubic(prog(t, ch.start - d / 2, d))
        if p > 0:
            tint = mix(tint, ch.tint, p)
    return tint


def draw_background(c, video, t):
    import cairo
    cx = c.ctx
    W, H = tk.W, tk.H
    if video.ground is not None:
        c.src(video.ground)
        cx.rectangle(0, 0, W, H)
        cx.fill()
        return
    drift = math.sin(t * 0.25) * 40  # slow living drift
    # light
    if c.dark < 1:
        c.src(tk.C["bg"])
        cx.rectangle(0, 0, W, H)
        cx.fill()
        tint = _tint_at(video, t)
        for (gx, gy, rad) in ((W * 0.95 + drift, H * 0.08, 1100), (W * 0.0 - drift, H * 0.72, 1150)):
            g = cairo.RadialGradient(gx, gy, 0, gx, gy, rad)
            g.add_color_stop_rgba(0, *tint[:3], 1)
            g.add_color_stop_rgba(1, *tint[:3], 0)
            cx.set_source(g)
            cx.rectangle(0, 0, W, H)
            cx.fill()
        warm = tk.C["bg_warm"]
        g = cairo.RadialGradient(W, H, 0, W, H, 1000)
        g.add_color_stop_rgba(0, *warm[:3], 1)
        g.add_color_stop_rgba(1, *warm[:3], 0)
        cx.set_source(g)
        cx.rectangle(0, 0, W, H)
        cx.fill()
    # dark (navy glow rising from the bottom)
    if c.dark > 0:
        cx.save()
        cx.push_group()
        c.src(tk.C["d_bg"])
        cx.rectangle(0, 0, W, H)
        cx.fill()
        glow = tk.C["d_glow"]
        g = cairo.RadialGradient(W * 0.35 + drift, H * 1.05, 0, W * 0.35 + drift, H * 1.05, 1300)
        g.add_color_stop_rgba(0, *glow[:3], 1)
        g.add_color_stop_rgba(0.6, *glow[:3], 0.45)
        g.add_color_stop_rgba(1, *glow[:3], 0)
        cx.set_source(g)
        cx.rectangle(0, 0, W, H)
        cx.fill()
        cx.pop_group_to_source()
        cx.paint_with_alpha(c.dark)
        cx.restore()


# ── HUD ─────────────────────────────────────────────────────────────────
def timecode(t, fps=tk.FPS):
    f = int(round(t * fps))
    ff = f % fps
    s = f // fps
    return f"{s // 3600:02d}:{(s // 60) % 60:02d}:{s % 60:02d}:{ff:02d}"


def draw_hud(c, video, t):
    F, L = tk.F, tk.L
    muted = c.theme("muted", "d_muted")
    size, ls, _ = tk.T["hud"]
    top, bot, x0, x1 = L["hud_top"], L["hud_bottom"], L["hud_x"], L["hud_right"]
    c.text(x0, top + 7, f"{video.brand} · {video.series}", F["mono"], size, muted, 1, ls)

    ch = video.chapter_at(t)
    if ch is not None:
        # chapter label (crossfade on change)
        p = out_expo(prog(t, ch.start, 0.5))
        prev = [x for x in video.chapters if x.start < ch.start]
        if prev and p < 1:
            c.text(x1, top + 7, prev[-1].hud, F["mono"], size, muted, 1 - p, ls, align="r")
        c.text(x1, top + 7, ch.hud, F["mono"], size, c.theme("ink2", "d_muted"), p, ls, align="r")
        # progress dots: one per numbered chapter
        nums = video.numbered()
        if nums and not ch.dark:
            n = len(nums)
            gap, r = L["dot_gap"], L["dot_r"]
            for i, nc in enumerate(nums):
                x = x1 - r - (n - 1 - i) * gap
                if ch.num is not None and nc.num == ch.num:
                    pp = out_expo(prog(t, ch.start, 0.5))
                    col = mix(tk.C["faint"], nc.color, pp)
                    c.circle(x, L["dots_y"], r * (1 + 0.25 * pp), col)
                elif ch.num is not None and nc.num < ch.num:
                    c.circle(x, L["dots_y"], r, tk.C["muted"])
                else:
                    c.circle(x, L["dots_y"], r, tk.C["faint"])

    # bottom-left: timecode • BPM ; bottom-right: format
    tc = timecode(t)
    w = c.text(x0, bot, tc, F["mono"], size, muted, 1, ls)
    c.circle(x0 + w + 16, bot - 6, 4, c.theme("accent", "d_accent"))
    c.text(x0 + w + 32, bot, f"{video.bpm} BPM", F["mono"], size, muted, 1, ls)
    c.text(x1, bot, f"{tk.W}×{tk.H} · {tk.FPS}FPS", F["mono"], size, muted, 1, ls, align="r")
