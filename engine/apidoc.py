"""`python -m engine api` → engine/API.md: one line per public function (signature + first docstring line).

Claude reads API.md instead of opening component sources / old scenes.py to recall names and arguments.
Regenerate after adding or changing a component (Claude may run it — text only).
"""
import inspect
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent


def _sig(obj):
    try:
        s = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(…)"
    return re.sub(r"<function (\w+) at 0x[0-9a-f]+>", r"\1", s.replace("'", '"'))   # fn defaults by name


def _doc(obj):
    d = inspect.getdoc(obj) or ""
    return d.strip().split("\n")[0][:150]


def _members(mod, names=None):
    out = []
    for name, obj in vars(mod).items():
        if name.startswith("_") or (names and name not in names):
            continue
        if (inspect.isfunction(obj) or inspect.isclass(obj)) and getattr(obj, "__module__", "") == mod.__name__:
            out.append((name, obj))
    return out


def build_api():
    import engine  # noqa: F401  (font setup)
    from engine import components, ease, draw, video, timing, camera
    exported = set(n for n in dir(components) if not n.startswith("_"))
    lines = ["# engine API — auto-generated by `python -m engine api` (don't edit by hand)", "",
             "One line per public function: `name(signature)` — first docstring line. Import from "
             "`engine.components` unless noted.", ""]
    # components, grouped by module (source file)
    mods = {}
    for name in sorted(exported):
        obj = getattr(components, name)
        m = getattr(obj, "__module__", "")
        if m.startswith("engine.components.") and (inspect.isfunction(obj) or inspect.isclass(obj)):
            mods.setdefault(m.split(".")[-1], []).append((name, obj))
    for m in sorted(mods):
        src = HERE / "components" / f"{m}.py"
        head = (inspect.getdoc(__import__(f"engine.components.{m}", fromlist=["x"])) or "").split("\n")[0]
        lines.append(f"## components/{m}.py — {head}" if head else f"## components/{m}.py")
        for name, obj in mods[m]:
            lines.append(f"- `{name}{_sig(obj)}` — {_doc(obj)}")
            if inspect.isclass(obj):
                for mn, mo in inspect.getmembers(obj, inspect.isfunction):
                    if not mn.startswith("_"):
                        lines.append(f"  - `.{mn}{_sig(mo)}` — {_doc(mo)}")
        lines.append("")
        assert src.exists(), src
    # namespace modules: `from engine.components import material` → material.body(...)
    for m in ("material",):
        mod = getattr(components, m)
        lines.append(f"## components/{m}.py (namespace `{m}.`) — {(inspect.getdoc(mod) or '').splitlines()[0]}")
        for name, obj in _members(mod):
            if inspect.isfunction(obj) and obj.__module__ == mod.__name__:
                lines.append(f"- `{m}.{name}{_sig(obj)}` — {_doc(obj)}")
        lines.append("")
    # core modules
    for title, mod, cls in (("ease (engine.ease)", ease, None), ("Video (engine.video)", video, "Video"),
                            ("Canvas `c` (engine.draw)", draw, "Canvas"), ("Timing `T` (engine.timing)", timing, None),
                            ("camera `v.camera` (engine.camera)", camera, "Camera")):
        lines.append(f"## {title}")
        if cls:
            k = getattr(mod, cls)
            for mn, mo in inspect.getmembers(k, inspect.isfunction):
                if not mn.startswith("_"):
                    lines.append(f"- `.{mn}{_sig(mo)}` — {_doc(mo)}")
        else:
            for name, obj in _members(mod):
                if inspect.isclass(obj):
                    for mn, mo in inspect.getmembers(obj, inspect.isfunction):
                        if not mn.startswith("_"):
                            lines.append(f"- `{name}.{mn}{_sig(mo)}` — {_doc(mo)}")
                else:
                    lines.append(f"- `{name}{_sig(obj)}` — {_doc(obj)}")
        lines.append("")
    out = HERE / "API.md"
    out.write_text("\n".join(lines))
    n = sum(1 for ln in lines if ln.startswith("- ") or ln.startswith("  - "))
    print(f"✓ {out}  ({n} entries, {len(lines)} lines)")
    return out


# Sections every scenes.py needs (headlines, beats, motion, cover, material + engine core). Everything else is a
# metaphor kit: list its names with `api index`, print its full lines only when the video uses it.
CORE = ("beats", "headline", "motion", "keynote", "craft", "pill", "cover", "material", "ease", "Video", "Canvas", "Timing",
        "camera")


def _sections():
    path = HERE / "API.md"
    if not path.exists():
        build_api()
    out, cur = {}, None
    for ln in path.read_text().splitlines():
        if ln.startswith("## "):
            m = ln[3:].split(" ", 1)[0]
            cur = m.removeprefix("components/").removesuffix(".py")
            out[cur] = [ln]
        elif cur and ln.strip():
            out[cur].append(ln)
    return out


def show(names):
    """`api core | index | <module> …` — print only those API.md sections (token-lean; text only, Claude may run).

    core  = sections every video needs · index = every other component module with just its names ·
    <module> (e.g. `hujan kasir`) = that module's full lines.
    """
    sec = _sections()
    for n in names:
        if n == "core":
            for k in CORE:
                print("\n".join(sec.get(k, [])) + "\n")
        elif n == "index":
            print("## component kits (names only — `api <module>` for signatures)")
            for k, lines in sec.items():
                if k in CORE:
                    continue
                fns = [ln.split("`")[1].split("(")[0] for ln in lines[1:] if ln.startswith("- `")]
                head = lines[0].split(" — ", 1)[-1][:90]
                print(f"- {k}: {head} → {', '.join(fns)}")
        elif n in sec:
            print("\n".join(sec[n]) + "\n")
        else:
            print(f"? no API section '{n}' (try: core, index, {', '.join(k for k in sec if k not in CORE)})")
    return 0
